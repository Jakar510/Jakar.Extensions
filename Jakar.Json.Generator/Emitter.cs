    private static void EmitOptions( CodeWriter code, ModelInfo model, Settings type )
    {
        string modifier = model.HasSerializableBase
                              ? "new "
                              : "";

        if ( !model.Skip.Contains("DefaultWriterOptions") ) { code.Line($"public static {modifier}{J}JsonWriterOptions DefaultWriterOptions => new() {{ Indented = {Bool(type.Indented == Values.ON)}, IndentChar = ({J}JsonIndentChar){type.IndentChar}, IndentSize = {type.IndentSize}, Escaping = ({J}JsonEscaping){type.Escaping}, MaxDepth = {type.MaxDepth} }};"); }

        if ( !model.Skip.Contains("DefaultReaderOptions") ) { code.Line($"public static {modifier}{J}JsonReaderOptions DefaultReaderOptions => new() {{ AllowComments = {Bool(type.AllowComments == Values.ON)}, AllowTrailingCommas = {Bool(type.AllowTrailingCommas == Values.ON)}, MaxDepth = {type.MaxDepth} }};"); }

        code.Line();
    }


