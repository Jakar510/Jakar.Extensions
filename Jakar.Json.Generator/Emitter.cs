    private static string Bool( bool value ) => value
                                                    ? "true"
                                                    : "false";

    /// <summary> A member name as an identifier (<c>@class</c> for keywords). </summary>
    public static string Id( string name ) => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None
                                                  ? "@" + name
                                                  : name;

